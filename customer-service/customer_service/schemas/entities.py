from datetime import datetime, timedelta
from typing import Any

from sqlalchemy import BigInteger, DateTime, ForeignKey, Index, Integer, String, text
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from customer_service.common.settings import get_settings
from customer_service.common.utils import get_uid, get_utcnow
from customer_service.schemas.enums import (
    ConversationMode,
    MessageType,
    TurnStatus,
)


class Base(DeclarativeBase):
    """SQLAlchemy declarative base for database entities.

    It shares table metadata and does not map to a table itself.
    """


class Conversation(Base):
    """Customer service conversation for a user.

    Records the service mode and activity timestamps, and links messages and
    processing turns.

    A user can have at most one AI, QUEUED, or HUMAN conversation at a time;
    closed conversations are not subject to this uniqueness constraint.

    Attributes:
        id: Internal 64-bit auto-increment primary key.
        uuid: Globally unique conversation identifier exposed to external systems.
        user_id: Identifier of the user who owns the conversation.
        mode: Conversation mode, one of AI, QUEUED, HUMAN, or CLOSED; defaults to AI.
        started_at: Conversation creation time in UTC with timezone.
        last_active_at: Last activity time, used to detect idle expiration.
    """

    __tablename__ = "conversations"
    __table_args__ = (
        # A user can have at most one active AI/QUEUED/HUMAN conversation;
        # CLOSED conversations are exempt from this uniqueness constraint.
        Index(
            "uq_open_conversation_per_user",
            "user_id",
            unique=True,
            postgresql_where=text("mode IN ('AI', 'QUEUED', 'HUMAN')"),
        ),
    )

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    uuid: Mapped[str] = mapped_column(
        String(80), unique=True, default=lambda: get_uid("conv")
    )
    user_id: Mapped[str] = mapped_column(String(40), index=True)
    mode: Mapped[str] = mapped_column(
        String(20), default=ConversationMode.AI, index=True
    )
    started_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=get_utcnow
    )
    last_active_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=get_utcnow, onupdate=get_utcnow
    )

    def update_last_active(self) -> None:
        """Update the last active time to now (UTC); used to detect expiration."""

        self.last_active_at = get_utcnow()

    def is_expired(
        self,
        expiration_seconds: int = get_settings().conversation_idle_timeout_seconds,
    ) -> bool:
        """Return whether the conversation has expired.

        AI conversations are closed automatically after the idle timeout and a
        new AI conversation is created. HUMAN and QUEUED conversations stay
        open until a human agent closes them manually.
        """
        return (
            self.mode == ConversationMode.AI
            and get_utcnow()
            > self.last_active_at + timedelta(seconds=expiration_seconds)
        )

    def close(self) -> None:
        """Close the conversation by setting its mode to CLOSED."""

        self.mode = ConversationMode.CLOSED

    def __repr__(self):
        return f"<Conversation id={self.id} uuid={self.uuid} user_id={self.user_id} mode={self.mode}>"


class Message(Base):
    """A message in a conversation, storing chat records.

    The database auto-increment primary key is separate from the business message
    identifier; the unique constraint on the business identifier prevents duplicate
    records caused by retries.

    Attributes:
        id: Internal 64-bit auto-increment primary key.
        uuid: Business message identifier; user messages are generated by the
            frontend and used for duplicate submission checks.
        conversation_id: Foreign key to the owning conversation (conversations.id).
        turn_id: Foreign key to the owning conversation turn (conversation_turns.id).
        role: Message sender role, one of USER, AI, or HUMAN.
        message_type: Message type, text or object; defaults to text.
        content: JSONB message content, such as text or structured message cards.
        created_at: Message creation time in UTC with timezone.
    """

    __tablename__ = "messages"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    uuid: Mapped[str] = mapped_column(String(80), unique=True)
    conversation_id: Mapped[int] = mapped_column(
        BigInteger,
        ForeignKey("conversations.id"),
        index=True,
    )
    turn_id: Mapped[int | None] = mapped_column(
        BigInteger,
        ForeignKey("conversation_turns.id"),
        nullable=True,
        index=True,
    )
    role: Mapped[str] = mapped_column(String(20))
    message_type: Mapped[str] = mapped_column(String(20), default=MessageType.TEXT)
    content: Mapped[dict[str, Any]] = mapped_column(JSONB)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=get_utcnow
    )

    def __repr__(self):
        return f"<Message id={self.id} uuid={self.uuid} conversation_id={self.conversation_id} turn_id={self.turn_id} role={self.role} message_type={self.message_type} content={self.content}>"


class ConversationTurn(Base):
    """A conversation turn in AI mode.

    A turn can contain one question and one answer, or multiple questions and
    one answer when the user interjects. A conversation can have at most one
    turn in each running state.

    Attributes:
        id: Internal 64-bit auto-increment primary key.
        uuid: Unique turn identifier exposed to external systems.
        conversation_id: Foreign key to the owning conversation (conversations.id).
        status: Turn status, see TurnStatus; starts as COLLECTING.
        revision: Turn revision, incremented whenever the turn status or content changes.
    """

    __tablename__ = "conversation_turns"
    __table_args__ = (
        # A conversation can have at most one turn in each running state
        # (COLLECTING or RUNNING); other states are exempt from this constraint.
        Index(
            "uq_collecting_turn_per_conversation",
            "conversation_id",
            unique=True,
            postgresql_where=text(f"status = '{TurnStatus.COLLECTING}'"),
        ),
        Index(
            "uq_executing_turn_per_conversation",
            "conversation_id",
            unique=True,
            postgresql_where=text(f"status = '{TurnStatus.RUNNING}'"),
        ),
    )
    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    uuid: Mapped[str] = mapped_column(
        String(80), unique=True, default=lambda: get_uid("turn")
    )
    conversation_id: Mapped[int] = mapped_column(
        BigInteger,
        ForeignKey("conversations.id"),
        index=True,
    )
    status: Mapped[str] = mapped_column(
        String(30), default=TurnStatus.COLLECTING, index=True
    )
    revision: Mapped[int] = mapped_column(Integer, default=0)

    def __repr__(self):
        return f"<ConversationTurn id={self.id} uuid={self.uuid} conversation_id={self.conversation_id} status={self.status} revision={self.revision}>"


class RealtimeEvent(Base):
    """Persisted realtime event.

    The realtime worker publishes events asynchronously to the target channel.
    Events can be stored in the same transaction as business data, and publish
    progress is tracked by published_at.

    Attributes:
        id: 64-bit auto-increment event primary key.
        target: Target channel; currently a user ID or the staff public channel.
        data: JSONB event payload to publish.
        created_at: Event creation time in UTC with timezone.
        published_at: Publish time; null means not yet marked as published.
    """

    __tablename__ = "realtime_events"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    target: Mapped[str] = mapped_column(String(80), index=True)
    data: Mapped[dict[str, Any]] = mapped_column(JSONB)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=get_utcnow
    )
    published_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), index=True
    )
