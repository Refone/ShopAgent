from enum import StrEnum


class UserRole(StrEnum):
    """User roles.

    Attributes:
        USER: Regular user.
        STAFF: Customer service staff.
        ADMIN: Administrator.
    """

    USER = "user"
    STAFF = "staff"
    ADMIN = "admin"


class MessageType(StrEnum):
    """Message types.

    Attributes:
        TEXT: Text message.
        OBJECT: Structured message, such as a product or order card.
    """

    TEXT = "text"
    OBJECT = "object"


class ConversationMode(StrEnum):
    """Conversation modes.

    Attributes:
        AI: AI mode, the user talks to the AI.
        QUEUED: Queued mode, waiting for a human agent.
        HUMAN: Human mode, the user talks to a human agent.
        CLOSED: Closed mode, the conversation has ended.

    """

    AI = "AI"
    QUEUED = "QUEUED"
    HUMAN = "HUMAN"
    CLOSED = "CLOSED"


class MessageRole(StrEnum):
    """Message roles.

    Attributes:
        USER: Message sent by the user.
        AI: Message generated by the AI.
        HUMAN: Message sent by a human agent.
    """

    USER = "USER"
    AI = "AI"
    HUMAN = "HUMAN"


class TurnStatus(StrEnum):
    """Turn statuses.

    Attributes:
        COLLECTING: Open state, collecting messages.
        RUNNING: In progress, processing messages.
        COMPLETED: Terminal state, processed successfully.
        FAILED: Terminal state, processing failed.
    """

    COLLECTING = "COLLECTING"
    RUNNING = "RUNNING"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
